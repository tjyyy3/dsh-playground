import { build } from 'esbuild';
import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('../', import.meta.url));
const output = new URL('../client.js', import.meta.url);
const result = await build({
  absWorkingDir: root,
  entryPoints: ['src/client/index.js'],
  bundle: true,
  write: false,
  format: 'cjs',
  platform: 'browser',
  target: 'es2022',
  charset: 'utf8',
  minify: false,
  keepNames: true,
  sourcemap: false,
  legalComments: 'none',
  external: ['react', '@deepseek-ai/dsh-client-ui-primitives', '@deepseek-ai/dsh-client-store'],
  banner: { js: '// Generated by npm run build:client. Edit src/client/ instead.\nwindow.__ModuleLoader__.load({\n  id: \'dsh-playground\',\n  factory(require) {\n    const module = { exports: {} };' },
  footer: { js: '    return module.exports.plugin;\n  },\n});' },
});
const generated = result.outputFiles[0].text;
if (process.argv.includes('--check')) {
  const current = await readFile(output, 'utf8');
  if (current.replace(/\r\n/g, '\n') !== generated) {
    throw new Error('client.js is stale. Run npm run build:client and commit the generated file.');
  }
  console.log('client.js matches src/client/.');
} else {
  await writeFile(output, generated);
  console.log('Built client.js.');
}
